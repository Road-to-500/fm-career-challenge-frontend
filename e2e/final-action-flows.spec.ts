async function screenshot(page: Page, project: string, state: string) {
  const folder = process.env.FMCC_UX_SCREENSHOTS
  if (!folder) return
  mkdirSync(folder, { recursive: true })
  const position = await page.evaluate(() => ({ x: window.scrollX, y: window.scrollY }))
  await page.evaluate(() => window.scrollTo({ top: 0, left: 0, behavior: 'instant' }))
  await page.screenshot({ path: join(folder, `${project}-${state}.png`), fullPage: true })
  await page.evaluate(({ x, y }) => window.scrollTo({ top: y, left: x, behavior: 'instant' }), position)
}

async function api(page: Page, path: string, method = 'GET', body?: object) {
  const result = await page.evaluate(async ({ path, method, body }) => {
    const headers: Record<string, string> = { 'Content-Type': 'application/json' }
    if (method !== 'GET') {
      const response = await fetch('/api/auth/csrf')
      headers['X-CSRF-TOKEN'] = (await response.json() as { requestToken: string }).requestToken
    }
    const response = await fetch(path, { method, headers, body: body ? JSON.stringify(body) : undefined })
    return { status: response.status, text: await response.text() }
  }, { path, method, body })
  expect(result.status, `${method} ${path}: ${result.text}`).toBeLessThan(300)
  return result.text ? JSON.parse(result.text) : undefined
}

async function navigateChallenge(page: Page, id: string, section = 'career') {
  await page.evaluate(async ({ id, section }) => {
    const modulePath = '/src/router.ts'
    const router = (await import(/* @vite-ignore */ modulePath)).default
    await router.push(`/challenges/${id}?section=${section}`)
  }, { id, section })
}

