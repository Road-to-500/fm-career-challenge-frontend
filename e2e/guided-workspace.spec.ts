import { expect, test } from '@playwright/test'

test.beforeEach(async ({ page }, testInfo) => {
  if (testInfo.project.name.endsWith('-light')) {
    await page.addInitScript(() => localStorage.setItem('fm-career-challenge-theme', 'light'))
  }
})

test('anonymous landing keeps personal workspace hidden and preserves invitation intent through public help', async ({ page }) => {
  await page.goto('/dashboard?invite=public-invite-intent')
  await expect(page.getByRole('heading', { name: 'Your Football Manager story. Season by season.' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Continue with Google' })).toBeVisible()
  await expect(page.getByText('You have an invitation waiting.')).toBeVisible()
  await expect(page.getByRole('button', { name: /^(New challenge|Create challenge|My challenges|Invitations)$/ })).toHaveCount(0)
  await expect(page.getByRole('navigation', { name: 'Main navigation' })).toHaveCount(0)
  await expect(page.getByRole('region', { name: 'Career statistics' })).toHaveCount(0)
  await page.getByRole('button', { name: 'See how it works' }).click()
  await expect(page).toHaveURL(/invite=public-invite-intent.*view=help/)
  await expect(page.getByRole('heading', { name: 'How FM Career Challenge works' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Continue with Google' })).toBeVisible()
  await page.goBack()
  await expect(page.getByRole('heading', { name: 'Your Football Manager story. Season by season.' })).toBeVisible()
  await page.getByRole('button', { name: 'See how it works' }).click()
  await page.getByRole('link', { name: 'FM Career Challenge home' }).click()
  await expect(page).toHaveURL('/dashboard?invite=public-invite-intent')
  await expect(page.getByRole('heading', { name: 'Your Football Manager story. Season by season.' })).toBeVisible()
})

test('workspace sections, legacy links and history retain the invitation query', async ({ page, request }) => {
  const response = await request.post('/api/_e2e/identities')
  expect(response.ok()).toBeTruthy()
  const identities = await response.json() as { owner: string }
  await page.context().addCookies([{ name: 'fmcc.e2e', value: identities.owner, url: 'http://127.0.0.1:5176' }])
  await page.goto('/dashboard?invite=workspace-intent#invitations')
  await expect(page).toHaveURL(/invite=workspace-intent.*view=invitations$/)
  await expect(page.getByLabel('Invitation code')).toHaveValue('workspace-intent')
  const navigation = page.getByRole('navigation', { name: 'Main navigation' })
  await navigation.getByRole('button', { name: 'My challenges' }).click()
  await expect(page).toHaveURL(/view=challenges/)
  await expect(page.getByRole('heading', { name: 'Challenges and drafts' })).toBeVisible()
  await expect(page.getByRole('region', { name: 'Career statistics' })).toHaveCount(0)
  await navigation.getByRole('button', { name: 'How it works' }).click()
  await expect(page.getByRole('heading', { name: 'How FM Career Challenge works' })).toBeVisible()
  await page.goBack()
  await expect(page).toHaveURL(/view=challenges/)
  await page.goBack()
  await expect(page.getByLabel('Invitation code')).toHaveValue('workspace-intent')
  await navigation.getByRole('button', { name: 'Overview' }).click()
  await expect(page).toHaveURL('/dashboard?invite=workspace-intent')
  await expect(page.getByRole('region', { name: 'Career statistics' })).toBeVisible()
})

test('Google sign-in return restores a waiting invitation when the callback drops its query', async ({ page, request }) => {
  const response = await request.post('/api/_e2e/identities')
  expect(response.ok()).toBeTruthy()
  const identities = await response.json() as { owner: string }
  await page.goto('/dashboard?invite=provider-return-intent')
  await expect(page.getByRole('button', { name: 'Continue with Google' })).toBeVisible()
  await page.context().addCookies([{ name: 'fmcc.e2e', value: identities.owner, url: 'http://127.0.0.1:5176' }])
  await page.route('**/api/auth/google', route => route.fulfill({
    contentType: 'text/html',
    body: '<script>window.location.replace("/dashboard")</script>',
  }))
  await page.getByRole('button', { name: 'Continue with Google' }).click()
  await expect(page).toHaveURL(/invite=provider-return-intent.*view=invitations/)
  await expect(page.getByLabel('Invitation code')).toHaveValue('provider-return-intent')
  await expect(page.getByRole('navigation', { name: 'Main navigation' })).toBeVisible()
  expect(await page.evaluate(() => sessionStorage.getItem('fmcc.pending-invitation'))).toBeNull()
})

test('a lower-division club start saves without a circular prerequisite and survives reload', async ({ page, request }) => {
  const response = await request.post('/api/_e2e/identities')
  expect(response.ok()).toBeTruthy()
  const identities = await response.json() as { owner: string }
  await page.context().addCookies([{ name: 'fmcc.e2e', value: identities.owner, url: 'http://127.0.0.1:5176' }])
  await page.goto('/dashboard')
  await page.getByRole('button', { name: 'Create challenge', exact: true }).click()
  const create = page.getByRole('dialog', { name: 'Start a new challenge' })
  await create.getByLabel('Challenge name').fill(`Club start ${Date.now()}`)
  await create.getByLabel('Starting season').fill('2025')
  await create.getByRole('button', { name: 'Create challenge' }).click()
  await page.getByRole('button', { name: 'Career', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Seasons', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Update season', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Set career start' }).click()
  const start = page.getByRole('dialog', { name: 'Career start' })
  await start.getByLabel('Starting situation').selectOption('Club')
  await expect(start.getByRole('button', { name: 'Save career start' })).toBeDisabled()
  await start.getByRole('button', { name: 'Add starting club' }).click()
  const club = page.getByRole('dialog', { name: 'Add a club to your career' })
  await club.getByLabel('Club name', { exact: true }).fill(`UX initial club ${Date.now()}`)
  await club.getByLabel('Choose a country from the catalog').selectOption('PT')
  await club.getByLabel('Division level', { exact: true }).fill('2')
  await expect(club.getByLabel('Starting season', { exact: true })).toContainText('2025/26 — Season 1')
  await club.getByRole('button', { name: 'Save club' }).click()
  await expect(club).toBeHidden()
  await expect(start).toBeVisible()
  await expect(start.getByLabel('Starting club')).not.toHaveValue('')
  await start.getByRole('button', { name: 'Save career start' }).click()
  await expect(start).toBeHidden()
  const id = new URL(page.url()).pathname.split('/').at(-1)
  const saved = await page.request.get(`/api/challenges/${id}/career`)
  const career = await saved.json() as { startingStatus: string; clubs: Array<{ startSeasonIndex: number; initialDivisionLevel: number }> }
  expect(career.startingStatus).toBe('Club')
  expect(career.clubs).toHaveLength(1)
  expect(career.clubs[0]).toMatchObject({ startSeasonIndex: 0, initialDivisionLevel: 2 })
  await page.reload()
  await page.getByRole('button', { name: 'Career', exact: true }).click()
  await expect(page.getByText('Starting club:', { exact: false })).toBeVisible()
  await expect(page.locator('.timeline-club-card')).toHaveCount(1)
  await page.locator('summary').filter({ hasText: 'International career and optional milestone evidence' }).click()
  await page.locator('summary').filter({ hasText: 'International career and optional milestone evidence' }).click()
  await expect(page.locator('.timeline-club-card')).toHaveCount(1)
})
